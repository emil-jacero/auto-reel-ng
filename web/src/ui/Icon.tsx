/**
 * An icon. Decorative (`aria-hidden`) unless it is given a `label`, which makes
 * it an image with that name — for an icon that is the only content of its control.
 */
export function Icon({ name, size = 16, label }: { name: IconName; size?: 16 | 20; label?: string }) {
  const semantics =
    label === undefined
      ? { 'aria-hidden': true as const }
      : { role: 'img' as const, 'aria-label': label }
  return (
    <svg
      className="icon"
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      focusable="false"
      {...semantics}
    >
      {PATHS[name]}
    </svg>
  )
}
